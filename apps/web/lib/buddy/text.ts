export type OkfKey = keyof typeof en;
/** A translation: the same keys as English (text.test.ts checks every language). */
export type OkfTable = Record<OkfKey, string>;

export const OKF_TEXT: Record<Lang, OkfTable> = { en, it, ru, ro, ja };

/** Sentences a client says its own way (the extension looks at a browser tab, not at a shared screen). */
export type TextSwap = Partial<Record<OkfKey, OkfKey>>;

/**
 * OK Filow's strings in one interface language: the one lookup every OK Filow surface uses (panel,
 * overlay, settings, page and remote notices). An unknown language or a missing key reads English;
 * `swap` lets a client say a sentence its own way.
 */
export function okfText(lang: string, swap: TextSwap = {}): (k: OkfKey) => string {
  const table: Partial<OkfTable> = OKF_TEXT[isLang(lang) ? lang : "en"];
  return (k) => {
    const key = swap[k] ?? k;
    return table[key] || en[key];
  };
}

