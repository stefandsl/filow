export const WB_TEXT: Record<"en" | "it", Record<WbKey, string>> = { en, it };

/** The string for `key` in `lang` (English for a language without a table yet), with {name} filled in. */
export function wbText(lang: string, key: WbKey, values: Record<string, string | number> = {}): string {
  const table = lang === "it" ? WB_TEXT.it : WB_TEXT.en;
  return (table[key] ?? WB_TEXT.en[key]).replace(/\{(\w+)\}/g, (m, name: string) => (name in values ? String(values[name]) : m));
}
