/** The string for `key` in `lang` (English for an unknown language), with {name} filled in. */
export function wbText(lang: string, key: WbKey, values: Record<string, string | number> = {}): string {
  const table = (WB_TEXT as Record<string, WbTable | undefined>)[lang] ?? WB_TEXT.en;
  return (table[key] || WB_TEXT.en[key]).replace(/\{(\w+)\}/g, (m, name: string) => (name in values ? String(values[name]) : m));
}
